    function renderCompendiumCards() {
        const grid = document.getElementById('compendium-cards-grid');
        if (!grid || !window.LORDRAN_300_DATABASE) return;

        const cat = window.activeCompendiumCategory || 'ALL';
        const q = window.compendiumSearchQuery || '';

        const filtered = window.LORDRAN_300_DATABASE.filter(item => {
            const matchCat = (cat === 'ALL' || item.category === cat);
            const matchQuery = !q || item.name.toLowerCase().includes(q) || item.desc.toLowerCase().includes(q) || item.title.toLowerCase().includes(q);
            return matchCat && matchQuery;
        });

        grid.innerHTML = filtered.map(item => {
            const catBadgeColor = item.category === 'ARMOR' ? '#ffd700' : (item.category === 'NPC' ? '#00ffaa' : '#ff5555');
            const catBadgeBg = item.category === 'ARMOR' ? 'rgba(212,175,55,0.15)' : (item.category === 'NPC' ? 'rgba(0,255,170,0.15)' : 'rgba(255,85,85,0.15)');

            let actionBtn = '';
            if (item.category === 'ARMOR') {
                actionBtn = `<button class="btn-fight-boss" onclick="window.compendiumInstance.equipArmor('${item.id}')" style="border-color: #ffd700; color: #fff3a8; padding: 6px 10px; font-size: 0.72rem; margin-right: 4px;">🛡️ EQUIP</button>`;
            } else if (item.category === 'NPC') {
                actionBtn = `<button class="btn-fight-boss" onclick="window.compendiumInstance.summonNPC('${item.id}')" style="border-color: #00ffaa; color: #a5ffbe; padding: 6px 10px; font-size: 0.72rem; margin-right: 4px;">🧙 SUMMON</button>`;
            } else {
                actionBtn = `<button class="btn-fight-boss" onclick="window.compendiumInstance.challengeMob('${item.id}')" style="border-color: #ff5555; color: #ffaaaa; padding: 6px 10px; font-size: 0.72rem; margin-right: 4px;">⚔️ FIGHT</button>`;
            }

            return `
                <div class="boss-card" style="border-color: rgba(255,255,255,0.12); padding: 10px;">
                    <div class="boss-card-info" style="gap: 12px;">
                        <div class="boss-card-icon" style="font-size: 1.8rem;">${item.icon}</div>
                        <div class="boss-card-text">
                            <div style="display: flex; align-items: center; gap: 8px;">
                                <span style="font-size: 0.65rem; font-weight: 800; padding: 2px 6px; border-radius: 3px; border: 1px solid ${catBadgeColor}; color: ${catBadgeColor}; background: ${catBadgeBg};">${item.category}</span>
                                <div class="boss-card-name" style="font-size: 0.88rem;">${item.name}</div>
                            </div>
                            <div class="boss-card-desc" style="font-size: 0.75rem; color: #b8b0a2; margin-top: 2px;">${item.desc}</div>
                            <div class="boss-card-stats" style="font-size: 0.72rem; color: #ffd778; margin-top: 3px;">${item.title}</div>
                        </div>
                    </div>
                    <div style="display: flex; gap: 6px; margin-top: 8px; justify-content: flex-end;">
                        ${actionBtn}
                        <button class="btn-fight-boss" onclick="window.compendiumInstance.spawnInWorld('${item.id}')" style="padding: 6px 10px; font-size: 0.72rem; border-color: #64b5f6; color: #bbdefb; background: rgba(20,40,70,0.5);">📦 SPAWN 3D</button>
                    </div>
                </div>
            `;
        }).join('');
    }

